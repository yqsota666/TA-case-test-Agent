export function checkDiscussionReply(reply) {
  if (typeof reply === 'string') reply=reply.replace(/\r\n/g,'\n').replace(/[ \t]+(?=\n|$)/g,'').trim();
  if(typeof reply!=='string' || reply.length<15 || reply.length>900 || /```|<\/?[A-Za-z][^>]*>|\[[^\]\n]+\]\([^)\n]+\)|^\s*#{1,6}\s/m.test(reply) ||
    /(?:我|我们|本助手|本系统|系统|AI)\s*(?:已|已经|现已)[^。！？\n]{0,20}(?:生成|制定|锁定|执行|提交|启动|完成|定稿|锁好|生成好|执行完)/i.test(reply) ||
    /(?:Plan|SOP|方案|测试)[^。！？\n]{0,6}(?:已|已经|现已)(?:生成|锁定|执行|完成|定稿)/i.test(reply)) {
    throw Object.assign(new Error('讨论回复内容或长度未通过校验，请重试原输入'),{code:'MODEL_OUTPUT_FORMAT'});
  }
  return reply;
}
